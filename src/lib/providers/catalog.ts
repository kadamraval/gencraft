let customUserModels: AIModel[] = []

export function registerCustomModel(model: AIModel): void {
  const existing = customUserModels.findIndex((m) => m.id === model.id)
  if (existing >= 0) {
    customUserModels[existing] = model
  } else {
    customUserModels.push(model)
  }
  try {
    if (typeof window !== 'undefined') {
      localStorage.setItem('gencraft_custom_models', JSON.stringify(customUserModels))
    }
  } catch {
    // LocalStorage quota or access error handled gracefully
  }
}

export function getCustomModels(): AIModel[] {
  if (customUserModels.length === 0 && typeof window !== 'undefined') {
    try {
      const stored = localStorage.getItem('gencraft_custom_models')
      if (stored) {
        customUserModels = JSON.parse(stored)
      }
    } catch {
      // LocalStorage quota or access error handled gracefully
    }
  }
  return customUserModels
}

export function getAllModels(): AIModel[] {
  const custom = getCustomModels()
  const liveSynced = getStoredSyncedModels()

  const map = new Map<string, AIModel>()
  MODEL_CATALOG.forEach((m) => map.set(m.id, m))
  liveSynced.forEach((m) => map.set(m.id, m))
  custom.forEach((m) => map.set(m.id, m))

  return Array.from(map.values())
}

/**
 * Retrieves all models belonging to a specific provider.
 */
export function getProviderModels(providerId: ProviderType | string): AIModel[] {
  const all = getAllModels()
  return all.filter((m) => m.provider === providerId)
}

/**
 * Checks whether a model is activated/enabled to appear in the Chat Model Selector.
 * By default (if user hasn't explicitly customized yet), all models are enabled.
 */
export function isModelEnabledForChat(modelId: string, enabledList?: string[]): boolean {
  if (!enabledList || enabledList.length === 0) return true
  return enabledList.includes(modelId)
}

